// Copies the Tabler icons the app uses (src/icons.ts) into src/tablerIcons.gen.ts, so the
// bundle carries only those. Run after adding an icon: npm run generate-icons
import { readFileSync, writeFileSync } from 'node:fs'
import { DRAWN_ICONS } from '../src/drawnIcons.ts'
import { ICON_TABLES, UI_ICONS } from '../src/icons.ts'

const outline = new URL('../node_modules/@tabler/icons/icons/outline/', import.meta.url)
const used = new Set([
  ...UI_ICONS,
  ...Object.values(ICON_TABLES).flatMap((table) => table.map(([icon]) => icon)),
])
const names = [...used].filter((name) => name && !(name in DRAWN_ICONS)).sort()

const icons = names.map((name) => {
  const svg = readFileSync(new URL(`${name}.svg`, outline), 'utf8')
  const body = svg
    .slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'))
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '')
    .replace(/\s+/g, ' ')
    .replace(/ \/>/g, '/>')
    .trim()
  return `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`
})

const license = readFileSync(new URL('../../LICENSE', outline), 'utf8').trim()
const version = JSON.parse(readFileSync(new URL('../../package.json', outline), 'utf8')).version

writeFileSync(
  new URL('../src/tablerIcons.gen.ts', import.meta.url),
  `// Generated by scripts/generate-icons.mjs from @tabler/icons ${version}; don't edit.
/*
${license}
*/
export const TABLER_ICONS: Record<string, string> = {
${icons.join('\n')}
}
`,
)
console.log(`${names.length} Tabler icons`)
